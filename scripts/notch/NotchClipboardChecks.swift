        for text in ["one", "two", "three", "two"] { history.add(NotchClip(content: .text(text))) }
        check(history.items.compactMap(\.text) == ["two", "three", "one"], "A text copied again moves to the front once")
        history.add(NotchClip(content: .text("four")))
        check(history.items.compactMap(\.text) == ["four", "two", "three"], "The oldest leaves past the limit")
        history.promote(history.items[2].id)
        check(history.items.compactMap(\.text) == ["three", "four", "two"], "Copying back moves an item to the front")
        history.limit = 1
        check(history.items.compactMap(\.text) == ["three"], "Lowering the limit trims at once")
        let start = Date(timeIntervalSince1970: 1_000_000)
        history.add(NotchClip(content: .text("ghp_secret"), expires: start.addingTimeInterval(60)))
        check(!history.expire(at: start.addingTimeInterval(59)) && history.items.count == 1, "A secret stays for its minute")
        check(history.expire(at: start.addingTimeInterval(60)) && history.items.isEmpty, "Then it leaves")

        // The watcher.
        let board = NSPasteboard(name: NSPasteboard.Name("NotchClipboardChecks.\(UUID().uuidString)"))
        defer { board.releaseGlobally() }
        var clock = start
        var access = NotchPasteAccess.allowed
        func copy(_ text: String, marked: String? = nil) {
            board.clearContents()
            board.setString(text, forType: .string)
            if let marked { board.setData(Data(), forType: NSPasteboard.PasteboardType(marked)) }
        }
        copy("before")
        let clipboard = NotchClipboard(pasteboard: board, now: { clock }, access: { access })
        clipboard.start()
        clipboard.poll()
        check(clipboard.history.items.isEmpty, "What was copied before the start is not news")
        var changes = 0
        let watch = clipboard.objectWillChange.sink { changes += 1 }
        clipboard.poll()
        clipboard.poll()
        check(changes == 0, "Polls with nothing new publish nothing, so nothing redraws")
        watch.cancel()
        copy("hello")
        clipboard.poll()
        check(clipboard.history.items.compactMap(\.text) == ["hello"], "A new copy is kept")
        clipboard.poll()
        check(clipboard.history.items.count == 1, "An unchanged count reads nothing")
        copy("hunter2", marked: "org.nspasteboard.ConcealedType")
        clipboard.poll()
        check(clipboard.history.items.compactMap(\.text) == ["hello"], "A concealed copy is never kept")
        let image = NSImage(size: NSSize(width: 4, height: 3), flipped: false) { rect in
            NSColor.red.setFill(); rect.fill(); return true
        }
        board.clearContents()
        board.writeObjects([image])
        clipboard.poll()
        check(clipboard.history.items.first.map { if case .image = $0.content { true } else { false } } == true,
              "A copied image is kept")
        copy("ghp_" + String(repeating: "aB3", count: 12))
        clipboard.poll()
        check(clipboard.history.items.first?.expires == start.addingTimeInterval(NotchClipFilter.secretLifetime),
              "A secret is kept with its expiry")
        clock = start.addingTimeInterval(NotchClipFilter.secretLifetime)
        clipboard.poll()
        check(clipboard.history.items.count == 2 && clipboard.history.items.allSatisfy { $0.expires == nil },
              "Polling drops it when its time is up")
        copy("ghp_" + String(repeating: "Qw7", count: 12))
        clipboard.poll()
        let late = clipboard.history.items[0].id
        clipboard.stop()
        clock = clock.addingTimeInterval(NotchClipFilter.secretLifetime + 60)
        copy("copied while asleep")
        clipboard.copy(late)
        check(board.string(forType: .string) == "copied while asleep" && clipboard.history.items.count == 2,
              "A secret whose time ran out while stopped cannot be copied back")
        clipboard.start()
        let hello = clipboard.history.items[1].id
        clipboard.copy(hello)
        check(board.string(forType: .string) == "hello" && clipboard.history.items.first?.id == hello,
              "Copying back writes the text and moves it to the front")
        clipboard.poll()
        check(clipboard.history.items.count == 2, "Eclipse's own copy is not taken as news")
        clipboard.history.items.forEach { clipboard.remove($0.id) }
        copy("ghp_" + String(repeating: "Zy9", count: 12))
        clipboard.poll()
        let beforeSecret = board.changeCount
        clipboard.copy(clipboard.history.items[0].id)
        check(board.types?.contains(NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")) == true
              && board.string(forType: .string)?.hasPrefix("ghp_Zy9") == true && board.changeCount == beforeSecret + 1,
              "A secret goes back marked concealed, text and mark in one write")
        clipboard.clear()
        access = .ask
        copy("asked")
        clipboard.poll()
        check(clipboard.history.items.isEmpty && clipboard.access == .ask, "Nothing is read while macOS would ask each time")
        access = .allowed
        copy("allowed")
        clipboard.poll()
        clipboard.stop()
        copy("asleep")
        clipboard.poll()
        check(!clipboard.running && clipboard.history.items.compactMap(\.text) == ["allowed"],
              "Stopping keeps the list and reads no more")
        clipboard.start()
        clipboard.poll()
        check(clipboard.history.items.compactMap(\.text) == ["allowed"], "A copy made while stopped is not news after a start")
        print("\(checks) clipboard checks passed")
    }
}
