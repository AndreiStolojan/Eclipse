import AppKit

/// One copied item on the Shelf page's Clipboard list.
struct NotchClip: Identifiable, Equatable {
    enum Content: Equatable {
        case text(String)
        case image(NSImage)
    }

    let id: UUID
    let content: Content
    /// The app that was frontmost when it was copied, if known.
    let source: String?
    /// Set for text that looks like a secret: it shows masked and leaves the list at this time.
    let expires: Date?

    init(id: UUID = UUID(), content: Content, source: String? = nil, expires: Date? = nil) {
        self.id = id
        self.content = content
        self.source = source
        self.expires = expires
    }

    var text: String? { if case .text(let text) = content { text } else { nil } }
}

/// Which copies are kept, decided from what the pasteboard says about them before any contents are read.
enum NotchClipFilter {
    /// Marker types password managers and other apps add to say a copy must not be kept
    /// (http://nspasteboard.org), plus 1Password's own and a common older one.
    static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType",
    ]
    /// Seconds a secret-looking text stays on the list.
    static let secretLifetime: TimeInterval = 60
    /// Longer copies are left out: the list shows one line, and checking one for secrets takes up to about 70 ms at
    /// this length, on the main thread.
    static let maxTextLength = 20_000
    static let maxImageBytes = 25_000_000

    /// Whether a copy with these pasteboard types is left out: a marked one, or files copied in Finder, which belong
    /// on the shelf as files.
    static func skips(_ types: [String]) -> Bool {
        types.contains { skippedTypes.contains($0) } || types.contains(NSPasteboard.PasteboardType.fileURL.rawValue)
    }

    /// Tokens of GitHub, GitLab, OpenAI and Anthropic, Slack, AWS, Google, SendGrid, npm and PyPI, a JWT and a private
    /// key, anywhere in the text: alone, in a command, a header or a configuration file.
    private static let secretPattern = try! NSRegularExpression(pattern: [
        #"\bgh[pousr]_[A-Za-z0-9]{20,}"#, #"\bgithub_pat_[A-Za-z0-9_]{20,}"#, #"\bglpat-[A-Za-z0-9_-]{20,}"#,
        #"\bsk-[A-Za-z0-9_-]{20,}"#, #"\bxox[abps]-[A-Za-z0-9-]{10,}"#, #"\b(?:AKIA|ASIA)[A-Z0-9]{16}\b"#,
        #"\bAIza[0-9A-Za-z_-]{35}"#, #"\bSG\.[A-Za-z0-9_-]{16,}\.[A-Za-z0-9_-]{16,}"#, #"\bnpm_[A-Za-z0-9]{30,}"#,
        #"\bpypi-[A-Za-z0-9_-]{30,}"#, #"\beyJ[A-Za-z0-9_-]{8,}\.eyJ[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}"#,
        #"-----BEGIN [A-Z ]*PRIVATE KEY-----"#,
    ].joined(separator: "|"))

    /// Credentials by their place, each pattern's first group being the value: the credential of an `Authorization`
    /// or `Proxy-Authorization` header, bare or quoted as in JSON; the password of a URL, as in
    /// `postgresql://admin:…@db`; curl's `-u user:password`, where a path after the colon is rsync's `host:/path`; and
    /// the value of `--password`, `--token` and similar options; and `-p` where it means a password: attached in
    /// mysql's `-psecret` (`-p dbname` asks instead), attached or after a space in `docker login -p secret`, never in
    /// `docker run -p 8080:80`. A value that only names a variable, as in
    /// `--password "$DOCKER_PASSWORD"`, is not one.
    private static let placedPatterns = [
        #"(?i:\b(?:proxy-)?authorization["']?\s*[:=]\s*["']?(?:(?:bearer|basic|token|digest)\s+)?([A-Za-z0-9._~+/=${}-]{8,}))"#,
        #"\b[A-Za-z][A-Za-z0-9+.-]{0,31}://[^\s/:@]+:([^\s/@]+)@"#,
        #"(?:^|\s)(?:-u\s*|--user[\s=]+)["']?[^\s:'"-][^\s:'"]*:(?![/~])([^\s'"]{4,})"#,
        #"(?i:(?:^|\s)--(?:password|passwd|pass|token|api-key|secret)(?:\s+|=)(["']?[^\s'"-][^\s'"]{3,}))"#,
        #"(?i:\b(?:mysql|mariadb|mysqldump|mysqladmin)\b[^\n|;&]{0,200}?\s-p(["']?[^\s'"-][^\s'"]{3,}))"#,
        #"(?i:\b(?:docker|podman|nerdctl|helm\s+registry)\s+login\b[^\n|;&]{0,200}?\s-p\s*(["']?[^\s'"-][^\s'"]{3,}))"#,
    ].map { try! NSRegularExpression(pattern: $0) }
    /// The value of a `Cookie` header or curl's `-b`, read cookie by cookie: one whose name has sess, sid, auth,
    /// token or jwt in it, such as `session`, `PHPSESSID` or `connect.sid`, and a value of eight or more characters
    /// is a credential. One pass of a single character class, so a long header costs a scan, not a search.
    private static let cookiePattern = try! NSRegularExpression(pattern:
        #"(?i)(?:\bcookie\s*:\s*|(?:^|\s)(?:-b|--cookie)[\s=]+["']?)([^\n'"]{1,4000})"#)

    /// A name, `=` or `:`, and a value: a `${…}` reference whole; a quoted one of four or more characters up to its
    /// closing quote, whatever it holds, as in `DB_PASSWORD="…"` or `"token": "…"`; or a bare one of six or more that
    /// ends at `&`, `?` or `;`, so the parameters of a URL and the statements of a shell line are read one by one. A
    /// name starts where no letter, digit or `_` precedes it, so after the dashes of `--password=…` too, and is at
    /// most 64 characters long, so a long word without `=` or `:` costs one bounded try per position, not one per
    /// pair.
    private static let assignmentPattern = try! NSRegularExpression(pattern:
        #"(?<![A-Za-z0-9_])([A-Za-z][A-Za-z0-9_-]{0,63})["']?\s*[=:]\s*(\$\{[^}\n]{1,200}\}|"[^"\n]{4,}"|'[^'\n]{4,}'|[^\s"'`&?;]{6,})"#)
    /// A value that only names a variable or a template field: `$NAME`, `${NAME}`, `${NAME:?message}`, `{{ name }}`.
    /// A fallback, as in `${NAME:-default}`, is checked itself.
    private static let referencePattern = #"^(?:\$[A-Za-z_][A-Za-z0-9_]*|\$\{[A-Za-z_][A-Za-z0-9_]*(?::?\?[^}]*)?\}|\{\{[^}]*\}\})$"#
    private static let fallbackPattern = try! NSRegularExpression(pattern: #"^\$\{[A-Za-z_][A-Za-z0-9_]*:?[-=+](.*)\}$"#)

    /// Whether a value only refers to a variable or a template field, holding no credential itself. A fallback of
    /// four or more characters, as in `${DB_PASSWORD:-changeme}`, is a credential.
    static func isReference(_ value: String) -> Bool {
        let bare = value.trimmingCharacters(in: CharacterSet(charactersIn: "\"'"))
        if bare.range(of: referencePattern, options: .regularExpression) != nil { return true }
        let range = NSRange(bare.startIndex..., in: bare)
        guard let match = fallbackPattern.firstMatch(in: bare, range: range),
              let fallback = Range(match.range(at: 1), in: bare) else { return false }
        return bare[fallback].count < 4
    }
    /// A declaration keyword right before a name, as in `let password: String`: with a bare value, the name is a
    /// variable, not a credential.
    private static let declarationPattern = try! NSRegularExpression(pattern: #"\b(?:let|var|const|val)\s+$"#)
    /// A name, `:`, what may be a type, as in `password: String`, `Optional[str]`, `str | None` or `string | null`,
    /// and an optional quoted initializer, ending where code would: at the end, a newline, `,`, `;`, `)`, `=`, `}` or
    /// `]`, so `password: Abcd1234?xyz` is no type. Whether it is a type at all is decided in `looksSecret`, so YAML's
    /// `password: hunter22` stays a value.
    private static let annotationPattern = try! NSRegularExpression(pattern: #"(?<![A-Za-z0-9_])([A-Za-z][A-Za-z0-9_-]{0,63})\s*:\s*("#
        + annotationType + #"(?:\s*\|\s*"# + annotationType + #"){0,3})(?:\s*=\s*(?:"([^"\n]*)"|'([^'\n]*)'))?"#
        + #"(?=\s*(?:$|[,;)=}\]\n]))"#)
    private static let annotationType = #"[A-Za-z][A-Za-z0-9_.]{0,40}(?:\[[^\]\n]{0,40}\]|<[^>\n]{0,40}>)?\??"#
    /// Type names that follow a name in a declaration or a signature, such as `password: String`.
    private static let typeNames: Set<String> = ["string", "str", "int", "number", "bool", "boolean", "data", "bytes",
                                                 "any", "object", "optional"]
    /// Last name parts that describe a credential instead of holding one: `token_type`, `password_policy`.
    private static let metadataWords: Set<String> = ["type", "policy", "length", "expiry", "expires", "expiration", "url",
                                                     "uri", "endpoint", "file", "path", "hint", "label", "format"]
    /// Name parts that make a value a credential on their own; `key` counts only beside a part of `keyQualifiers`,
    /// as in `api_key` or `ACCESS_KEY`, never alone, inside a word such as `keyboard`, or in `primary_key`.
    private static let credentialWords: Set<String> = ["token", "secret", "password", "passwd", "pwd", "passphrase",
                                                       "credential", "credentials", "apikey", "auth"]
    private static let keyQualifiers: Set<String> = ["api", "access", "private", "signing", "encryption", "client",
                                                     "master", "license", "app", "service", "account", "deploy", "ssh"]

    /// Text that holds a credential: a known token or key anywhere in it, a value after a credential
    /// name, or, when the whole text is one word, a random-looking one. A git hash, a UUID, a URL, a path,
    /// an identifier, a command or prose is not.
    static func looksSecret(_ text: String) -> Bool {
        let range = NSRange(text.startIndex..., in: text)
        if secretPattern.firstMatch(in: text, range: range) != nil { return true }
        for pattern in placedPatterns {
            let found = pattern.matches(in: text, range: range).contains { match in
                Range(match.range(at: 1), in: text).map { !isReference(String(text[$0])) } ?? false
            }
            if found { return true }
        }
        let cookies = cookiePattern.matches(in: text, range: range).contains { match in
            guard let header = Range(match.range(at: 1), in: text) else { return false }
            return text[header].split(separator: ";").contains { cookie in
                let pair = cookie.split(separator: "=", maxSplits: 1)
                guard pair.count == 2 else { return false }
                let name = pair[0].trimmingCharacters(in: .whitespaces).lowercased()
                return ["sess", "sid", "auth", "token", "jwt"].contains(where: name.contains)
                    && pair[1].trimmingCharacters(in: .whitespaces).count >= 8
            }
        }
        if cookies { return true }
        // A type annotation of a credential name counts only with a literal of four or more characters, as in
        // `let password: String = "…"`; without one, as in `password: Optional[str] = None`, it is code.
        var annotated: Set<Int> = []
        for match in annotationPattern.matches(in: text, range: range) {
            guard let name = Range(match.range(at: 1), in: text), let type = Range(match.range(at: 2), in: text),
                  isCredentialName(String(text[name])) else { continue }
            let declared = declarationPattern.firstMatch(in: text, range: NSRange(text.startIndex..<name.lowerBound, in: text)) != nil
            guard declared || text[type].contains(where: { "[<|?".contains($0) })
                    || typeNames.contains(text[type].lowercased()) else { continue }
            let literal = [3, 4].lazy.compactMap { Range(match.range(at: $0), in: text) }.first
            if let literal, text[literal].count >= 4 { return true }
            annotated.insert(match.range(at: 1).location)
        }
        let named = assignmentPattern.matches(in: text, range: range).contains { match in
            guard let name = Range(match.range(at: 1), in: text), let value = Range(match.range(at: 2), in: text),
                  !annotated.contains(match.range(at: 1).location), isCredentialName(String(text[name])) else { return false }
            // A quoted value is a literal, a credential even in a declaration. A bare one after `let` or a type alone
            // is code.
            // A reference to a variable, as in `DB_PASSWORD=${DB_PASSWORD}`, holds no credential itself.
            if isReference(String(text[value])) { return false }
            if text[value].first == "\"" || text[value].first == "'" { return true }
            let declared = declarationPattern.firstMatch(in: text, range: NSRange(text.startIndex..<name.lowerBound, in: text)) != nil
            let type = String(text[value]).trimmingCharacters(in: CharacterSet(charactersIn: ",;)?!")).lowercased()
            return !declared && !typeNames.contains(type)
        }
        if named { return true }
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        return !trimmed.contains(where: \.isWhitespace) && looksRandom(trimmed)
    }

    /// Whether a name's parts, split at `_`, `-` and case changes (`dbPassword`, `DBPassword`), name a credential,
    /// unless its last part only describes one (`token_type`).
    static func isCredentialName(_ name: String) -> Bool {
        let characters = Array(name)
        var parts: [String] = []
        var current = ""
        for (index, character) in characters.enumerated() {
            if character == "_" || character == "-" {
                parts.append(current); current = ""
                continue
            }
            // A capital after a small letter starts a part, and so does the last capital of a run before a small one.
            let next = index + 1 < characters.count ? characters[index + 1] : nil
            if character.isUppercase, let last = current.last,
               last.isLowercase || last.isUppercase && next?.isLowercase == true {
                parts.append(current); current = ""
            }
            current.append(character)
        }
        parts.append(current)
        let words = parts.filter { !$0.isEmpty }.map { $0.lowercased() }
        if let last = words.last, metadataWords.contains(last) { return false }
        return words.contains(where: credentialWords.contains) || words.contains("key") && words.contains(where: keyQualifiers.contains)
    }

    /// One word of 32 to 4096 characters with digits and at least two of lower case, upper case and symbols, and at
    /// least 4 bits of entropy per character: generated passwords and keys, not identifiers, URLs or paths.
    private static func looksRandom(_ word: String) -> Bool {
        guard (32...4096).contains(word.count), !word.contains("://"), !looksLikePath(word),
              word.contains(where: \.isNumber) else { return false }
        let classes = [word.contains(where: \.isLowercase), word.contains(where: \.isUppercase),
                       word.contains { !$0.isLetter && !$0.isNumber }]
        return classes.filter { $0 }.count >= 2 && entropy(word) >= 4
    }

    /// An absolute, home or relative path, or folders ending in a file name with an extension. A key with slashes,
    /// as base64 has, ends in no extension.
    private static func looksLikePath(_ word: String) -> Bool {
        if ["/", "~", "./", "../"].contains(where: word.hasPrefix) { return true }
        guard word.contains("/"), let last = word.split(separator: "/").last else { return false }
        return last.range(of: #"^[A-Za-z0-9_-]+\.[A-Za-z0-9]{1,6}$"#, options: .regularExpression) != nil
    }

    /// Shannon entropy in bits per character.
    static func entropy(_ text: String) -> Double {
        let counts = Dictionary(text.map { ($0, 1) }, uniquingKeysWith: +)
        let total = Double(text.count)
        return counts.values.reduce(0) { sum, count in
            let p = Double(count) / total
            return sum - p * log2(p)
        }
    }

    /// A secret as the list shows it: its first four characters and dots.
    static func masked(_ text: String) -> String {
        String(text.trimmingCharacters(in: .whitespacesAndNewlines).prefix(4)) + "••••••••"
    }
}

/// The list itself, newest first: a text copied again moves to the front instead of showing twice, and the oldest
/// leave past `limit`.
struct NotchClipHistory: Equatable {
    private(set) var items: [NotchClip] = []
    var limit = 10 {
        didSet { trim() }
    }

    mutating func add(_ clip: NotchClip) {
        if let text = clip.text { items.removeAll { $0.text == text } }
        items.insert(clip, at: 0)
        trim()
    }

    /// Moves an item copied back to the front.
    mutating func promote(_ id: NotchClip.ID) {
        guard let index = items.firstIndex(where: { $0.id == id }) else { return }
        items.insert(items.remove(at: index), at: 0)
    }

    mutating func remove(_ id: NotchClip.ID) { items.removeAll { $0.id == id } }

    mutating func removeAll() { items = [] }

    /// Drops secrets whose time is up; returns whether any left.
    mutating func expire(at now: Date) -> Bool {
        let count = items.count
        items.removeAll { $0.expires.map { $0 <= now } ?? false }
        return items.count != count
    }

    private mutating func trim() {
        if items.count > max(limit, 1) { items.removeLast(items.count - max(limit, 1)) }
    }
}

/// Eclipse's paste access, from System Settings > Privacy & Security > Paste (macOS 15.4 and later): not asked yet,
/// ask on every read, always allowed or always denied. Earlier systems never ask.
enum NotchPasteAccess: Equatable {
    case notAsked, ask, allowed, denied

    init(_ pasteboard: NSPasteboard) {
        guard #available(macOS 15.4, *) else { self = .allowed; return }
        switch pasteboard.accessBehavior {
        case .ask: self = .ask
        case .alwaysAllow: self = .allowed
        case .alwaysDeny: self = .denied
        default: self = .notAsked
        }
    }

    /// Whether Eclipse reads copies: before the first prompt, which the read then causes once, or once allowed.
    var reads: Bool { self == .notAsked || self == .allowed }
}

/// Watches the general pasteboard while the clipboard history is on and keeps what is copied, in memory only.
/// macOS posts no event when the clipboard changes, so it reads `changeCount`, a plain integer, twice a second, and
/// the contents only when that count moves. Since macOS 15.4 reading another app's copy asks the user unless Eclipse
/// is set to Always Allow in Privacy & Security > Paste; the first read shows that prompt once, and while the
/// setting is Ask or Deny nothing is read, so the user is not asked on every copy.
@MainActor
final class NotchClipboard: ObservableObject {
    @Published private(set) var history = NotchClipHistory()
    /// The system's paste access for Eclipse, refreshed on each change and by `refreshAccess`.
    @Published private(set) var access: NotchPasteAccess
    var limit: Int {
        get { history.limit }
        set { history.limit = newValue }
    }

    private let pasteboard: NSPasteboard
    private let now: () -> Date
    private let readAccess: () -> NotchPasteAccess
    private var timer: Timer?
    private var lastCount: Int
    /// The count after Eclipse's own copy back, which is not news.
    private var ownCount: Int?

    static let interval: TimeInterval = 0.5
    /// A row of the Shelf page's list.
    static let rowHeight: Double = 28

    /// Rows of the Shelf page's list that fit an open notch whose body below the camera is `bodyHeight` tall: the
    /// page's 8 pt top and 4 pt bottom insets and its 36 pt footer leave the rest to rows. More rows scroll.
    static func visibleRows(bodyHeight: Double) -> Int {
        max(Int((bodyHeight - 48) / rowHeight), 0)
    }
    /// System Settings' Privacy & Security > Paste.
    static let settingsURL = URL(string: "x-apple.systempreferences:com.apple.preference.security?Privacy_Pasteboard")!

    /// Checks pass a private pasteboard and a fixed access and clock.
    init(pasteboard: NSPasteboard = .general, now: @escaping () -> Date = Date.init,
         access: (() -> NotchPasteAccess)? = nil) {
        self.pasteboard = pasteboard
        self.now = now
        readAccess = access ?? { NotchPasteAccess(pasteboard) }
        self.access = readAccess()
        lastCount = pasteboard.changeCount
    }

    var running: Bool { timer != nil }

    /// Starts from the clipboard as it is: what was copied before is not news. A secret whose time ran out while
    /// stopped, as through sleep, leaves at once.
    func start() {
        guard timer == nil else { return }
        expireSecrets()
        lastCount = pasteboard.changeCount
        refreshAccess()
        let timer = Timer(timeInterval: Self.interval, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.2
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    /// Stops watching and keeps the list, as through sleep; `clear` forgets it.
    func stop() {
        timer?.invalidate()
        timer = nil
    }

    func refreshAccess() {
        let current = readAccess()
        if current != access { access = current }
    }

    /// One tick while running: expire secrets, then take a new copy if the count moved.
    func poll() {
        guard running else { return }
        expireSecrets()
        let count = pasteboard.changeCount
        guard count != lastCount else { return }
        lastCount = count
        refreshAccess()
        guard count != ownCount, access.reads else { return }
        capture()
    }

    /// Reads the new copy unless its types say to leave it, which needs no access. The type is picked from the
    /// advertised ones first, so each copy costs exactly one read, the only one that may ask for access.
    private func capture() {
        let types = pasteboard.types ?? []
        guard !NotchClipFilter.skips(types.map(\.rawValue)) else { return }
        let source = NSWorkspace.shared.frontmostApplication?.localizedName
        if types.contains(.string) {
            let text = pasteboard.string(forType: .string)
            refreshAccess()
            guard let text, !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
                  text.count <= NotchClipFilter.maxTextLength else { return }
            let secret = NotchClipFilter.looksSecret(text)
            history.add(NotchClip(content: .text(text), source: source,
                                  expires: secret ? now().addingTimeInterval(NotchClipFilter.secretLifetime) : nil))
        } else if let type = [NSPasteboard.PasteboardType.png, .tiff].first(where: types.contains) {
            let data = pasteboard.data(forType: type)
            refreshAccess()
            guard let data, data.count <= NotchClipFilter.maxImageBytes, let image = NSImage(data: data) else { return }
            history.add(NotchClip(content: .image(image), source: source))
        }
    }

    /// Puts an item back on the clipboard and moves it to the front. A secret goes back marked concealed, so other
    /// clipboard managers leave it alone too; text and mark are one item written at once, so none reads the text
    /// before the mark is there.
    func copy(_ id: NotchClip.ID) {
        expireSecrets()
        guard let clip = history.items.first(where: { $0.id == id }) else { return }
        pasteboard.clearContents()
        switch clip.content {
        case .text(let text):
            let item = NSPasteboardItem()
            item.setString(text, forType: .string)
            if clip.expires != nil {
                item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
            }
            pasteboard.writeObjects([item])
        case .image(let image):
            pasteboard.writeObjects([image])
        }
        ownCount = pasteboard.changeCount
        lastCount = ownCount ?? lastCount
        history.promote(id)
    }

    /// Drops secrets whose time is up, touching the published list only when one is, so an idle poll redraws nothing.
    private func expireSecrets() {
        let now = now()
        guard history.items.contains(where: { $0.expires.map { $0 <= now } ?? false }) else { return }
        _ = history.expire(at: now)
    }

    func remove(_ id: NotchClip.ID) { history.remove(id) }

    func clear() { history.removeAll() }
}
